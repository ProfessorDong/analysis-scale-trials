"""What CALGB 40603 did to a continuous endpoint, and what it cost.

The trial (Sikov et al., J Clin Oncol 2015) has a binary primary endpoint,
pathologic complete response, and collected residual cancer burden as a
continuous secondary index. The publication never analyses RCB continuously:
it reports the dichotomy "RCB class 0 or I" as a percentage.

That matters for Proposition 1. The invariance is stated for strictly
increasing f. A threshold is monotone but not strictly increasing, and it is
exactly the transformation that breaks the invariance, because it destroys the
orderings the probabilistic index depends on. This script measures how far the
index moves when the trial's own dichotomy is applied to its own data.

Writes NaturePortfolio/data/calgb_numbers.tex.
"""

from __future__ import annotations

import glob
import itertools
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT.parent / "NaturePortfolio" / "data"
SRC = "data/ProjectDataSphere/Breast_Allianc_2009_162/**/PoC_treated2_xomic.csv"

# RCB class boundaries from Symmans et al., J Clin Oncol 2007;25:4414-4422.
# The two cutpoints were "determined sequentially by maximizing the profile
# log-likelihood of a multivariate Cox model": 3.28 is the 87th percentile of
# that cohort and 1.36 the 40th.  They are data-derived, in 382 patients at one
# centre, for a prognostic purpose.  Used here only to count values that
# contradict their own recorded class, never to alter an analysis.
CLASS_RANGE = {"RCB-0": (0.0, 0.0), "RCB-I": (0.0, 1.36),
               "RCB-II": (1.36, 3.28), "RCB-III": (3.28, 6.0)}


def rcb_formula(finv: float, dprim: float, ln: int, dmet: float) -> float:
    """The index as Symmans defines it.

    RCB = 1.4 (f_inv d_prim)^0.17 + [4(1 - 0.75^LN) d_met]^0.17.

    Both terms carry the exponent 0.17, so the index is compressed by
    construction and cannot reach large values.  This is what makes a recorded
    10.0 impossible rather than merely extreme.
    """
    return 1.4 * (finv * dprim) ** 0.17 + (4 * (1 - 0.75 ** ln) * dmet) ** 0.17


def pi(a: np.ndarray, b: np.ndarray) -> float:
    """P(B > A) with ties at one half."""
    u = stats.mannwhitneyu(b, a, alternative="two-sided")
    return float(u.statistic / (len(a) * len(b)))


def main() -> None:
    path = glob.glob(str(ROOT / SRC), recursive=True)
    if not path:
        raise SystemExit("CALGB 40603 data not found; it is under a data use agreement")
    d = pd.read_csv(path[0], low_memory=False)

    n_all, n_rcb = len(d), int(d.RCB.notna().sum())
    avail = pd.crosstab(d.indrx, d.RCB.notna())
    p_avail = stats.chi2_contingency(avail).pvalue

    inconsistent = 0
    for cls, (lo, hi) in CLASS_RANGE.items():
        s = d.loc[d.RCBclass.astype(str) == cls, "RCB"].dropna()
        inconsistent += int(((s < lo - 1e-9) | (s > hi + 1e-9)).sum())

    ev = d[d.RCB.notna() & d.RCBclass.astype(str).ne("RCB-UNEV")].copy()
    ev["minimal"] = ev.RCBclass.astype(str).isin(["RCB-0", "RCB-I"]).astype(int)

    shifts = []
    for i, j in itertools.combinations(sorted(ev.indrx.unique()), 2):
        a, b = ev[ev.indrx == i], ev[ev.indrx == j]
        if len(a) < 20 or len(b) < 20:
            continue
        # Lower RCB is better, so orient larger-is-better before comparing.
        c = pi(-a.RCB.to_numpy(float), -b.RCB.to_numpy(float))
        k = pi(a.minimal.to_numpy(float), b.minimal.to_numpy(float))
        shifts.append((i, j, c, k, k - c))

    biggest = max(shifts, key=lambda r: abs(r[4]))
    crossers = [r for r in shifts if (r[2] - 0.5) * (r[3] - 0.5) < 0]

    # The largest value the formula can return under inputs already past the
    # bounds of plausibility: a whole-breast tumour bed entirely replaced by
    # invasive cancer, 100 positive nodes, and a 100 mm nodal metastasis.
    ceiling = rcb_formula(1.0, 500.0, 100, 100.0)

    m = {
        "calgbCeiling": f"{ceiling:.1f}",
        "calgbN": f"{n_all}", "calgbRCB": f"{n_rcb}",
        "calgbRCBpct": f"{100 * n_rcb / n_all:.0f}",
        "calgbAvailP": f"{p_avail:.2f}",
        "calgbInconsistent": f"{inconsistent}",
        "calgbContrasts": f"{len(shifts)}",
        "calgbMaxShift": f"{abs(biggest[4]):.3f}",
        "calgbMaxFrom": f"{biggest[2]:.3f}", "calgbMaxTo": f"{biggest[3]:.3f}",
        "calgbCrossers": f"{len(crossers)}",
    }
    if crossers:
        c = max(crossers, key=lambda r: abs(r[4]))
        m["calgbCrossFrom"] = f"{c[2]:.3f}"
        m["calgbCrossTo"] = f"{c[3]:.3f}"

    with open(OUT / "calgb_numbers.tex", "w") as fh:
        fh.write("% Generated by Paper2_Reanalysis/code/calgb40603_dichotomy.py.\n"
                 "% Do not edit by hand; rerun the script instead.\n")
        for k, v in m.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

    for k, v in m.items():
        print(f"  {k:20s} {v}")
    print("\nper-contrast shift in the probabilistic index under the published dichotomy:")
    for i, j, c, k, s in shifts:
        print(f"   arms {i} vs {j}: {c:.3f} -> {k:.3f}  ({s:+.3f})")


if __name__ == "__main__":
    main()
