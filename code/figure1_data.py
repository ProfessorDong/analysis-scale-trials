"""Data and labels for Figure 1, the invariance asymmetry.

Figure 1 is the only quantitative figure in the paper whose numbers were not
produced by a script.  Its densities and its five printed labels existed only
as .dat files and hand-typed TikZ nodes, and one label had drifted: the
treatment mean is 4.85496, which the figure rounded to 4.86.

The example is two lognormal arms chosen so that the mean contrast reverses
sign under the log transform while the probabilistic index does not move:

    log Y_C ~ N(0.5, 0.6^2)      log Y_T ~ N(0.3, 1.6^2)

The treated arm has the lower location but far greater dispersion, so
exp(mu + sigma^2/2) puts its mean above the control's while its median sits
below.  Everything the figure states follows in closed form; nothing is
simulated, so there is no seed and no Monte Carlo error.

Grids are generated over exactly the axis window each panel displays, so the
filled regions close flush with the axis edges rather than short of them.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy import stats

OUT = Path(__file__).resolve().parents[2] / "NaturePortfolio" / "data"

MU_C, SIG_C = 0.5, 0.6
MU_T, SIG_T = 0.3, 1.6

# The axis windows in figures/fig1.tex.  Kept here so the data and the axes
# cannot disagree.
# The raw grid starts at exactly 0, where the lognormal density is 0, so the
# treated arm's curve rises from the axis instead of beginning mid-air at the
# 0.227 it takes at x = 0.01.  Its mode is at 0.104 and is sharp, so the raw
# grid is finer than the log one to resolve it.
RAW_LO, RAW_HI, N_RAW = 0.0, 11.0, 1201
LOG_LO, LOG_HI, N_LOG = -4.2, 4.8, 501


def main() -> None:
    mean_c = np.exp(MU_C + SIG_C**2 / 2)
    mean_t = np.exp(MU_T + SIG_T**2 / 2)
    # P(Y_T > Y_C) = P(log Y_T - log Y_C > 0); the difference of two
    # independent normals is normal, so this is exact.
    pi = stats.norm.cdf((MU_T - MU_C) / np.hypot(SIG_T, SIG_C))

    x = np.linspace(RAW_LO, RAW_HI, N_RAW)
    fc = stats.lognorm.pdf(x, SIG_C, scale=np.exp(MU_C))
    ft = stats.lognorm.pdf(x, SIG_T, scale=np.exp(MU_T))
    np.savetxt(OUT / "dens_raw.dat", np.column_stack([x, fc, ft]),
               header="x fc ft", comments="")

    u = np.linspace(LOG_LO, LOG_HI, N_LOG)
    gc = stats.norm.pdf(u, MU_C, SIG_C)
    gt = stats.norm.pdf(u, MU_T, SIG_T)
    np.savetxt(OUT / "dens_log.dat", np.column_stack([u, gc, gt]),
               header="u gc gt", comments="")

    # Share of the treated arm to the right of the panel, which is the mass
    # that carries its mean and is not visible.  The figure says so.
    tail = 1 - stats.lognorm.cdf(RAW_HI, SIG_T, scale=np.exp(MU_T))
    below = stats.lognorm.cdf(mean_t, SIG_T, scale=np.exp(MU_T))

    macros = {
        "figMuC": f"{MU_C}", "figSigC": f"{SIG_C}",
        "figMuT": f"{MU_T}", "figSigT": f"{SIG_T}",
        "figEC": f"{mean_c:.2f}", "figET": f"{mean_t:.2f}",
        "figECx": f"{mean_c:.3f}", "figETx": f"{mean_t:.3f}",
        "figRawDiff": f"{mean_t - mean_c:+.2f}",
        "figLogC": f"{MU_C:.2f}", "figLogT": f"{MU_T:.2f}",
        "figLogDiff": f"{MU_T - MU_C:+.2f}",
        "figPinv": f"{pi:.3f}",
        "figTail": f"{100 * tail:.0f}",
        "figBelow": f"{100 * below:.0f}",
    }
    with open(OUT / "fig1_numbers.tex", "w") as fh:
        fh.write("% Generated by Paper2_Reanalysis/code/figure1_data.py.\n"
                 "% Do not edit by hand; rerun the script instead.\n")
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

    for k, v in macros.items():
        print(f"  {k:12s} {v}")
    print(f"\nwrote dens_raw.dat, dens_log.dat, fig1_numbers.tex to {OUT}")


if __name__ == "__main__":
    main()
